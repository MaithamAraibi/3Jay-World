"""Generate deterministic, asset-free flock routes for the meadow ambience.

This is a build-time authoring helper only; the browser renders every bird from
procedural Three.js geometry. Run from the repository root with:

    python multiplayer/tools/generate_flight_paths.py
"""
from __future__ import annotations

import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUTPUT = ROOT / "multiplayer/src/client/engine/flight-paths.ts"


def routes(count: int = 7) -> list[dict[str, float]]:
    """Return reproducible, spread-out elliptical flock routes."""
    result = []
    golden_angle = math.pi * (3.0 - math.sqrt(5.0))
    for i in range(count):
        angle = i * golden_angle + 0.35
        result.append({
            "radiusX": round(34.0 + (i % 3) * 11.0, 2),
            "radiusZ": round(27.0 + ((i + 1) % 4) * 8.0, 2),
            "height": round(10.0 + (i % 4) * 3.3, 2),
            "phase": round(angle, 5),
            "speed": round((0.045 + (i % 3) * 0.012) * (1 if i % 2 else -1), 5),
            "flockSize": 3 + i % 3,
            "seed": 1907 + i * 271,
        })
    return result


def main() -> None:
    rows = routes()
    lines = [
        "// Generated by multiplayer/tools/generate_flight_paths.py; do not hand-edit.",
        "// Deterministic procedural bird paths; no image or model assets are used.",
        "export const BIRD_ROUTES = [",
    ]
    for row in rows:
        fields = ", ".join(f"{key}: {value}" for key, value in row.items())
        lines.append(f"  {{ {fields} }},")
    lines.extend(["] as const;", ""])
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {len(rows)} deterministic flock routes to {OUTPUT}")


if __name__ == "__main__":
    main()
